#!/usr/bin/env python3
"""Generate lib/gunsnprices/unicode_tables.ex: the Unicode facts of Python's `re` and `str` that Erlang/Elixir differ on.

The package matches Python's results, so these tables are taken from the Python standard library:

* decimal digits (what Python's `\\d` matches and `int()` reads), as ranges of ten starting at each zero;
* whitespace (Python's `\\s` and `str.isspace()`, which also cover U+001C..U+001F);
* the Cased and Case_Ignorable characters that decide the final sigma in `str.lower()` ("ΑΣ" -> "ας").

Run from the package root:

    python3 tools/gen_tables.py > lib/gunsnprices/unicode_tables.ex
"""
import re
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110001):
        ok = cp <= 0x10FFFF and not (0xD800 <= cp <= 0xDFFF) and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def pcre_class(rs):
    """Body of a PCRE character class for the ranges, e.g. \\x{30}-\\x{39}\\x{660}-\\x{669}."""
    return "".join("\\x{%X}" % a if a == b else "\\x{%X}-\\x{%X}" % (a, b) for a, b in rs)


def ex_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("#{", "\\#{") + '"'


def main():
    digit = re.compile(r"\d")
    space = re.compile(r"\s")
    digits = ranges(lambda c: bool(digit.match(c)))
    assert all(b - a + 1 == 10 or (b - a + 1) % 10 == 0 for a, b in digits), digits
    zeros = [z for a, b in digits for z in range(a, b + 1, 10)]
    assert all(unicodedata.digit(chr(z)) == 0 for z in zeros)
    spaces = ranges(lambda c: bool(space.match(c)))
    assert spaces == ranges(str.isspace)

    def final(s):
        return s.lower()[-1] == "\u03c2"

    # see the comment in the generated module for why these two tests give the sets
    cased = ranges(lambda c: final(c + "\u03a3"))
    ignorable = ranges(lambda c: final("A" + c + "\u03a3") and not final(c + "\u03a3"))

    w = sys.stdout.write
    w("# @generated by tools/gen_tables.py from the Python %s standard library (Unicode %s). Do not edit.\n"
      % (sys.version.split()[0], unicodedata.unidata_version))
    w("defmodule GunsNPrices.UnicodeTables do\n")
    w("  @moduledoc false\n\n")
    w("  # Python's \\d: Unicode decimal digits (category Nd), as a PCRE class body.\n")
    w("  def digit_class, do: %s\n\n" % ex_string(pcre_class(digits)))
    w("  # The zero of every run of ten decimal digits, ascending.\n")
    w("  def digit_zeros, do: %s\n\n" % ("{" + ", ".join("0x%X" % z for z in zeros) + "}"))
    w("  # Python's \\s and str.isspace(), as a PCRE class body.\n")
    w("  def space_class, do: %s\n\n" % ex_string(pcre_class(spaces)))
    w("  # str.lower() turns U+03A3 into a final sigma when a cased letter comes before it and none after it, skipping\n")
    w("  # case-ignorable characters on both sides. Tested on Python: c + \"\\u03a3\" ends in a final sigma exactly when c\n")
    w("  # is cased and not case-ignorable; \"A\" + c + \"\\u03a3\" also does when c is case-ignorable.\n")
    w("  def cased_class, do: %s\n\n" % ex_string(pcre_class(cased)))
    w("  def case_ignorable_class, do: %s\n" % ex_string(pcre_class(ignorable)))
    w("end\n")


if __name__ == "__main__":
    main()
